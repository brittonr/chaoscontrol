//! Pure explicit selection of the immutable coarse clock/CPU profile.
use super::*;

pub(super) const DEFAULT_KERNEL_CMDLINE: &[u8] = b"console=ttyS0 earlyprintk=serial \
    clocksource=tsc tsc=reliable \
    lpj=6000000 \
    nokaslr noapic nosmp \
    nohpet \
    randomize_kstack_offset=off norandmaps \
    random.trust_cpu=off random.trust_bootloader=off \
    kfence.sample_interval=0 \
    no_hash_pointers \
    virtio_mmio.device=4K@0xd0000000:5 \
    virtio_mmio.device=4K@0xd0001000:6 \
    virtio_mmio.device=4K@0xd0002000:7 \
    panic=0\0";

const COARSE_CLOCK_TOKENS: [&str; 3] = ["noapictimer", "clocksource=jiffies", "notsc"];
const COARSE_CLOCK_TOKEN_BYTES: usize = "noapictimer clocksource=jiffies notsc".len() + 1;

fn clock_token_conflicts(token: &str) -> bool {
    (token.starts_with("clocksource=") && token != "clocksource=jiffies")
        || token.starts_with("clock=")
        || token == "tsc"
        || token.starts_with("tsc=")
        || token == "hpet=force"
}

fn validated_clock_inputs(
    config: &VmConfig,
    allow_template: bool,
) -> Result<(&str, &str), VmError> {
    let command_bytes = config.cmdline.strip_suffix(&[0]).unwrap_or(&config.cmdline);
    let command = std::str::from_utf8(command_bytes).map_err(|_| VmError::ProgressCapability {
        message: "coarse profile requires a UTF-8 kernel command".into(),
    })?;
    let extra = config.extra_cmdline.as_deref().unwrap_or("");
    let template = allow_template && config.cmdline == DEFAULT_KERNEL_CMDLINE;
    if command.contains('\0')
        || extra.contains('\0')
        || (!template && command.split_ascii_whitespace().any(clock_token_conflicts))
        || extra.split_ascii_whitespace().any(clock_token_conflicts)
    {
        return Err(VmError::ProgressCapability {
            message: "kernel command conflicts with the selected coarse jiffies/notsc/noapictimer profile".into(),
        });
    }
    Ok((command, extra))
}

/// Admission rechecks the actual declared inputs even when callers bypass the
/// explicit profile helper. This validation borrows configuration without copies.
pub(super) fn validate_coarse_clock_configuration(config: &VmConfig) -> Result<(), VmError> {
    let (_, extra) = validated_clock_inputs(config, false)?;
    if COARSE_CLOCK_TOKENS.iter().any(|required| {
        !extra
            .split_ascii_whitespace()
            .any(|token| token == *required)
    }) {
        return Err(VmError::ProgressCapability {
            message: "coarse profile requires explicit noapictimer, clocksource=jiffies and notsc boot inputs".into(),
        });
    }
    Ok(())
}

impl VmConfig {
    /// Apply a separately selected, immutable coarse CPU/clock policy.
    ///
    /// The byte-identical built-in command is a constructor template, not an
    /// operator override: explicit profile application replaces its strict TSC
    /// clock tokens. Any non-template command or extra clock conflict rejects
    /// before configuration mutation. No mode, budget, watchdog or journal bound
    /// is inferred or reset. The extra tokens also bind the actual Linux command
    /// generated by the VM's existing topology-aware loader.
    pub fn apply_kvm_debug_boundary_profile(
        &mut self,
        profile_id: BoundaryProfileId,
    ) -> Result<(), VmError> {
        if self.smp_progress_mode != ProgressMode::KvmDebugBoundary
            || !matches!(self.smp_progress_budget,
                ProgressBudget::KvmBoundaries { profile_id: configured, count: 1.. }
                    if configured == profile_id)
            || self.num_vcpus < 2
            || self.smp_entry_watchdog_microseconds == 0
            || self.smp_entry_watchdog_microseconds > (i64::MAX / 1000) as u64
            || self.smp_schedule_journal_limit == 0
        {
            return Err(VmError::ProgressCapability {
                message: "explicit coarse mode, matching positive boundary budget, SMP topology, finite entry watchdog and positive journal bound are required before profile application".into(),
            });
        }
        let template = self.cmdline == DEFAULT_KERNEL_CMDLINE;
        let (command, extra) = validated_clock_inputs(self, true)?;
        if COARSE_CLOCK_TOKENS.iter().all(|required| {
            command
                .split_ascii_whitespace()
                .any(|token| token == *required)
                && extra
                    .split_ascii_whitespace()
                    .any(|token| token == *required)
        }) {
            self.cpu.hide_tsc = true;
            self.cpu.hide_hypervisor = true;
            self.cpu.tsc_mode = crate::cpu::TscAdvanceMode::PerExit;
            return Ok(());
        }

        let mut profiled_command = String::with_capacity(command.len() + COARSE_CLOCK_TOKEN_BYTES);
        for token in command.split_ascii_whitespace() {
            if template && matches!(token, "clocksource=tsc" | "tsc=reliable") {
                continue;
            }
            if !profiled_command.is_empty() {
                profiled_command.push(' ');
            }
            profiled_command.push_str(token);
        }
        for token in COARSE_CLOCK_TOKENS {
            if !profiled_command
                .split_ascii_whitespace()
                .any(|existing| existing == token)
            {
                if !profiled_command.is_empty() {
                    profiled_command.push(' ');
                }
                profiled_command.push_str(token);
            }
        }
        profiled_command.push('\0');

        let mut profiled_extra = String::with_capacity(extra.len() + COARSE_CLOCK_TOKEN_BYTES);
        profiled_extra.push_str(extra);
        for token in COARSE_CLOCK_TOKENS {
            if !extra
                .split_ascii_whitespace()
                .any(|existing| existing == token)
            {
                if !profiled_extra.is_empty() {
                    profiled_extra.push(' ');
                }
                profiled_extra.push_str(token);
            }
        }
        self.cmdline = profiled_command.into_bytes();
        self.extra_cmdline = Some(profiled_extra);
        self.cpu.hide_tsc = true;
        self.cpu.hide_hypervisor = true;
        self.cpu.tsc_mode = crate::cpu::TscAdvanceMode::PerExit;
        Ok(())
    }
}
